"""
007 Main results comparison table (Exp 1) — Voronoi baseline

Reads static allocation (Voronoi) + Exp 0 summary,
and generates paper Table 1 / A1 / A2 / A3.

All methods are based on Voronoi partitioning.

Usage:
    python 007_exp1_main_results_table.py
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

STATIC_DIR = SCRIPT_DIR / 'results' / 'static_allocation'
EXP0_DIR = SCRIPT_DIR / 'results' / 'exp0_kfold_prior'
SUMMARY_DIR = EXP0_DIR / 'summary'
OUTPUT_DIR = SCRIPT_DIR / 'results' / 'exp1_main_table'
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

SEEDS = [42, 123, 456]
ALL_LOCATIONS = [
    'London',
    'TLH2', 'TLH3', 'TLJ1', 'TLF1', 'TLF2',
    'TLC1', 'TLC2', 'TLD6', 'TLG1', 'TLG2', 'TLE4',
    'TLH1', 'TLE3', 'TLD3', 'TLD4',
]


def load_static_metrics():
    """Load static allocation CSVs (generated by 003)."""
    result = {}
    for metric in ['rmse', 'mae', 'corr']:
        path = STATIC_DIR / f'all_regions_{metric}.csv'
        if path.exists():
            result[metric] = pd.read_csv(path, index_col=0)
        else:
            print(f'[Warning] static metrics not found: {path}')
            result[metric] = pd.DataFrame()
    return result


def load_exp0_per_seed(config_name, metric):
    """Load kfold_test_{metric}.csv for each seed of a single config; returns list[DataFrame]."""
    dfs = []
    for seed in SEEDS:
        path = EXP0_DIR / f'seed_{seed}' / config_name / f'kfold_test_{metric}.csv'
        if path.exists():
            dfs.append(pd.read_csv(path, index_col=0))
    return dfs


def compute_mean_std(dfs, method, region_cols):
    """Compute the mean±std of a method across regions, aggregated over seeds."""
    values = []
    for df in dfs:
        if method in df.index:
            values.append(df.loc[method, region_cols].values.astype(float))
    if not values:
        return None, None
    arr = np.array(values)
    return arr.mean(axis=0), arr.std(axis=0)


def format_mean_std(mean_val, std_val):
    """Format as a mean±std string."""
    if mean_val is None:
        return '—'
    return f'{mean_val:.4f}±{std_val:.4f}'


def build_main_table():
    """Build the main results comparison table (Voronoi baseline)."""
    print('=' * 60)
    print('Building Exp 1 main results table (Voronoi baseline)...')
    print('=' * 60)

    static = load_static_metrics()

    # Static method rows (all Voronoi baseline)
    static_methods = {
        'Uni': 'voronoi',
        'GPM': 'voronoi_gpm',
        'UniP': 'voronoi_prox2',
        'UniN': 'voronoi_ntl',
        'UniNP': 'voronoi_prox2_ntl',
        'GPMpostP': 'voronoi_prox2_gpm',
        'GPMpostN': 'voronoi_ntl_gpm',
        'GPMpostNP': 'voronoi_prox2_ntl_gpm',
    }

    # GNN method -> (config, method name in kfold_csv) mapping (all Voronoi baseline)
    gnn_configs = {
        'GNN': ('baseline', 'voronoi_GNN'),
        'GNNpostN': ('baseline', 'voronoi_ntl_GNN'),
        'GNNpostP': ('baseline', 'voronoi_prox_GNN'),
        'GNNpostNP': ('baseline', 'voronoi_ntl_prox_GNN'),
        'GNNpriorN': ('ntl', 'voronoi_GNN'),
        'GNNpriorP': ('proximity', 'voronoi_GNN'),
        'GNNpriorNP': ('ntl_prox', 'voronoi_GNN'),
    }

    # Build the combined table
    rows = []

    for metric in ['rmse', 'mae', 'corr']:
        metric_rows = []

        # Static methods (no seed variation, std = std dev across the 16 regions)
        for label, method in static_methods.items():
            if metric in static and method in static[metric].index:
                vals = static[metric].loc[method, ALL_LOCATIONS].values.astype(float)
                mean_val = vals.mean()
                std_val = vals.std()
                metric_rows.append({
                    'label': label,
                    'method': method,
                    'type': 'static',
                    'metric': metric,
                    'mean': round(mean_val, 4),
                    'std': round(std_val, 4),
                    'formatted': format_mean_std(mean_val, std_val),
                })

        # GNN methods (aggregated across seeds)
        for label, (config_name, method) in gnn_configs.items():
            dfs = load_exp0_per_seed(config_name, metric)
            if not dfs:
                metric_rows.append({
                    'label': label, 'method': method, 'type': 'gnn',
                    'metric': metric, 'mean': None, 'std': None, 'formatted': '—',
                })
                continue

            region_cols = [c for c in dfs[0].columns if c in ALL_LOCATIONS]
            mean_arr, std_arr = compute_mean_std(dfs, method, region_cols)

            if mean_arr is not None:
                grand_mean = mean_arr.mean()
                grand_std = mean_arr.std()
                metric_rows.append({
                    'label': label, 'method': method, 'type': 'gnn',
                    'metric': metric,
                    'mean': round(grand_mean, 4),
                    'std': round(grand_std, 4),
                    'formatted': format_mean_std(grand_mean, grand_std),
                })
            else:
                metric_rows.append({
                    'label': label, 'method': method, 'type': 'gnn',
                    'metric': metric, 'mean': None, 'std': None, 'formatted': '—',
                })

        rows.extend(metric_rows)

    # Output Table 1
    table_df = pd.DataFrame(rows)
    pivot = table_df.pivot_table(
        index=['label', 'method', 'type'],
        columns='metric',
        values='formatted',
        aggfunc='first',
    ).reset_index()

    # Sort
    order = list(static_methods.keys()) + list(gnn_configs.keys())
    pivot['sort_key'] = pivot['label'].map({k: i for i, k in enumerate(order)})
    pivot = pivot.sort_values('sort_key').drop(columns='sort_key')

    out_path = OUTPUT_DIR / 'table1_main_results.csv'
    pivot.to_csv(out_path, index=False)
    print(f'\nTable 1 saved to: {out_path}')
    print(pivot.to_string(index=False))

    # Table A1/A2/A3: per-region detail tables (all Voronoi baseline)
    print(f'\n--- Appendix tables: per-region detailed values ---')
    for metric in ['rmse', 'mae', 'corr']:
        detail_rows = []

        # Static methods
        for label, method in static_methods.items():
            if metric in static and method in static[metric].index:
                row = {'label': label, 'method': method}
                for loc in ALL_LOCATIONS:
                    row[loc] = round(float(static[metric].loc[method, loc]), 4)
                detail_rows.append(row)

        # GNN methods
        for label, (config_name, method) in gnn_configs.items():
            dfs = load_exp0_per_seed(config_name, metric)
            if not dfs:
                continue
            region_cols = [c for c in dfs[0].columns if c in ALL_LOCATIONS]
            mean_arr, _ = compute_mean_std(dfs, method, region_cols)
            if mean_arr is not None:
                row = {'label': label, 'method': method}
                for i, loc in enumerate(region_cols):
                    row[loc] = round(mean_arr[i], 4)
                detail_rows.append(row)

        if detail_rows:
            detail_df = pd.DataFrame(detail_rows)
            # Appendix table numbering: A1=RMSE, A2=MAE, A3=Corr
            suffix_map = {'rmse': 'a1', 'mae': 'a2', 'corr': 'a3'}
            detail_path = OUTPUT_DIR / f'table_{suffix_map[metric]}_per_region_{metric}.csv'
            detail_df.to_csv(detail_path, index=False)
            print(f'  {metric}: {detail_path}')

    print(f'\nExp 1 complete, output: {OUTPUT_DIR}')


if __name__ == '__main__':
    build_main_table()
