"""021 - German Börde phase-diagram points (completing the three-country flagship phase diagram).

Background: the phase-diagram points for the UK (240 points) and Australia
(180 points) cases have already been merged into
uk_au_phase_points_merged.csv (420 rows, with a hook left for a German
addition). This step computes the German case's phase-diagram points to
complete the three-country flagship phase diagram: the UK's GNN x
multiplicative points fall on the hurt side, Australia's fall on the help
side -- Germany's GNN x multiplicative points are expected to also fall on
the hurt side (019 measured GNNpostN worsening by +64% and GNNpostNP by
+193%). If the theoretical prediction agrees with the observed sign in all
three cases, then the three countries are three points on the **same
theoretical line**.

═══ Definitions (identical to the UK and Australia cases) ═══
- Per substation:
    rho_j = (d_true_j + eps) / (d_base_j + eps)   -- residual ratio
    F_j = (d_corr_j + eps) / (d_base_j + eps)     -- effective correction factor
  eps = total regional demand x 1e-6 (protects against log(0); the count of
  protected samples is recorded in the output).
- Alignment rho = Pearson corr(log F, log rho_resid); sigma_r = std(log
  rho_resid), sigma_c = std(log F) (numpy population standard deviation,
  ddof=0).
- Delta RMSE = RMSE(corrected) - RMSE(base), where RMSE is computed on the
  **raw** (not eps-protected) allocation values via scu.evaluate_allocation
  (actual_col='p_mw', the same convention as the German 003/019 scripts).
- Theoretical prediction predicted_help <=> rho > sigma_c/(2*sigma_r);
  observed actual_help <=> delta RMSE < 0.

═══ Combination space (Germany = single Börde region, 13 substations) ═══
Base in {Uniform, GPM, GNN x 3 seeds (baseline config)} x signal in
{N, P, NP} (multiplicative apply_standard_multiplicative) -> 1 x 3 x
(2 + 3) = 15 rows.
n = 13 substations -- the sample size for estimating rho is small; this is
reported as-is (a small-sample case worth flagging explicitly), with no
statistical inference performed (consistent with the paper's Germany
section).

═══ Implementation path (reused directly from 019, zero change to numerical
    semantics) ═══
The correction-factor construction and Voronoi aggregation are reused by
importing the 019 module: CRS monkeypatch (EPSG:25832), 'Name' -> 'ITL3'
column alias, and the same load_boerde / compute_uniform_base /
compute_gpm_base functions and frozen scu formulas.

═══ Built-in verification checks (guard against drift in the base/correction
    pipeline; same approach as the Australia case, plus a dual anchor
    against 019) ═══
(1) 4-decimal-place frozen anchor: the 8 static arms are checked against
    003's boerde_static_metrics.csv, and the 4 GNN arms are checked per
    seed against 005's metrics.csv (stored at 4 decimal places -> tolerance
    5e-5 + 1e-9, same as 019).
(2) Full-precision pipeline anchor: all 20 RMSE values (bases + corrected
    arms x seeds) are checked against 019's de_full_matrix.csv (stored at
    full precision, deterministic on the same CPU pipeline -> tolerance
    1e-9).
Any failed check raises an error immediately (an incorrect base invalidates
everything downstream).

═══ Three-country merge (the paper's complete flagship phase-diagram data) ═══
Reads Australia's uk_au_phase_points_merged.csv (UK 240 + AU 180, transcribed
without recomputation, read-only) and appends the 15 DE rows to produce
three_country_phase_points.csv (435 rows).

═══ Deviations from the UK/AU conventions (recorded in summary.deviations) ═══
1. Single region, single fold: the GNN base is 005's
   grid_demands['gnn_demand'] (baseline config), i.e. the training region's
   own prediction (Germany has no k-fold test fold) -- fold='-', which
   differs from the UK/AU test-fold convention and is reported as such.
2. Demand convention = p_mw (MW); the regional demand 'Demand (MVA)' is
   derived by summing substation p_mw per Gemeinde (same formula as 003) --
   d_true and the total regional demand share the same source (whereas
   UK/AU use independent statistical sources).
3. The CRS/aliasing adaptation reuses 019 (EPSG:25832 monkeypatch, Voronoi
   working_crs=3857).
4. n=13 substations, single region: the sampling error on rho is large
   (Fisher z SE = 1/sqrt(n-3) ~= 0.316); the sample size is recorded
   numerically in summary.small_sample_registration.

All verdict fields are generated by numeric rules rather than entered by
hand; the verdict thresholds match the UK case: value >= 0.9 -> supported;
>= 0.5 -> partially_supported; otherwise not_supported.
This step has no source of randomness (deterministic post-processing); runs
entirely on CPU (capped at 4 threads). All upstream frozen artifacts are
treated as read-only.

Outputs:
    results/de_phase_points.csv              -- 15 phase-diagram points
        (schema = country + the same 18 columns as the UK case, aligned
        column-for-column with the merged data)
    results/three_country_phase_points.csv   -- 435-point three-country merge
        (UK 240 + AU 180 + DE 15; the paper's complete flagship phase-diagram
        data)
    results/de_phase_summary.json            -- confusion matrix + DE
        placement verification + consistency with the +64%/+193% observed
        worsening + three-country merged accuracy + small-sample
        registration + verification report

Usage:
    python 021_de_phase_points.py    (allocategnn env, any working directory)
"""

