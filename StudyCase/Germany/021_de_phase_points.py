# ---------------------------------------------------------------------------
# Alignment statistics (ported verbatim from the UK/Australia cases'
# alignment_stats function -- the definitions must match exactly)
# ---------------------------------------------------------------------------
def alignment_stats(d_true: np.ndarray, d_base: np.ndarray,
                    d_corr: np.ndarray, eps: float) -> dict:
    """Compute substation-level alignment statistics for one (base, signal) combination (same as the UK case).

    The ratio-based quantities are computed in log space; the difference
    quantities use raw values. eps is only used to protect the
    ratio/logarithm computation -- d_true - d_base in the difference
    convention uses the raw values.
    """
    d_true = np.asarray(d_true, dtype=float)
    d_base = np.asarray(d_base, dtype=float)
    d_corr = np.asarray(d_corr, dtype=float)
    n = len(d_true)
    assert n >= 3, f"Number of substations {n} < 3, cannot compute correlation"

    # eps-protection counts (number of samples that were <= 0 before protection)
    n_prot_true = int((d_true <= 0).sum())
    n_prot_base = int((d_base <= 0).sum())
    n_prot_corr = int((d_corr <= 0).sum())
    n_prot_any = int(((d_true <= 0) | (d_base <= 0) | (d_corr <= 0)).sum())

    # Ratio convention (log space)
    log_rho = np.log((d_true + eps) / (d_base + eps))
    log_f = np.log((d_corr + eps) / (d_base + eps))

    if np.std(log_f) == 0 or np.std(log_rho) == 0:
        raise RuntimeError("log F or log rho has zero variance -- the correlation coefficient is undefined, check this combination")

    pearson_log = float(pearsonr(log_f, log_rho)[0])
    spearman_log = float(spearmanr(log_f, log_rho)[0])

    # sigma_r / sigma_c (phase-diagram coordinates; population std, ddof=0, matching the UK case's convention)
    sigma_r = float(np.std(log_rho))
    sigma_c = float(np.std(log_f))

    return {
        "n_substations": n,
        "eps": float(eps),
        "n_eps_protected_true": n_prot_true,
        "n_eps_protected_base": n_prot_base,
        "n_eps_protected_corrected": n_prot_corr,
        "n_eps_protected_any": n_prot_any,
        "pearson_log": pearson_log,
        "spearman_log": spearman_log,
        "sigma_r": sigma_r,
        "sigma_c": sigma_c,
        "sigma_ratio": sigma_c / sigma_r,
    }


# ---------------------------------------------------------------------------
# Single-base analysis (a German-parameterized version of the Australia
# case's analyse_base function)
# ---------------------------------------------------------------------------
def analyse_base(ctx: dict, d_true: np.ndarray, eps: float,
                 base_demand: np.ndarray, base_type: str, base_id: str,
                 seed, fold) -> list:
    """Compute alignment statistics and delta RMSE for one base x three signals, returning a list of records."""
    grid_gdf = ctx["grid_gdf"]
    region_gdf = ctx["region_gdf"]
    subs_gdf = ctx["subs_gdf"]
    assignment = ctx["assignment"]

    subs_base = scu.aggregate_by_assignment(subs_gdf, assignment, base_demand)
    d_base = subs_base["allocated_demand"].values.astype(float)
    m_base = scu.evaluate_allocation(subs_base, actual_col=DEMAND_COL)

    rows = []
    for signal in SIGNALS:
        corrected = scu.apply_standard_multiplicative(
            base_demand, ctx["factors"][signal], grid_gdf, region_gdf)
        subs_corr = scu.aggregate_by_assignment(subs_gdf, assignment, corrected)
        d_corr = subs_corr["allocated_demand"].values.astype(float)
        m_corr = scu.evaluate_allocation(subs_corr, actual_col=DEMAND_COL)

        stats = alignment_stats(d_true, d_base, d_corr, eps)
        rows.append({
            "base_type": base_type,
            "base_id": base_id,
            "seed": seed,
            "fold": fold,
            "location": LOCATION,
            "signal": signal,
            **stats,
            "rmse_base": float(m_base["rmse"]),
            "rmse_corrected": float(m_corr["rmse"]),
            "delta_rmse": float(m_corr["rmse"] - m_base["rmse"]),
        })
    return rows


# ---------------------------------------------------------------------------
# Frozen-value verification checks (guard against drift in the base
# reconstruction; same approach as the Australia case, plus a dual anchor
# against 019)
# ---------------------------------------------------------------------------
def _check_anchor(dev: float, tol: float, what: str, anchor_log: list) -> None:
    """Record one verification check and raise if the deviation exceeds tolerance."""
    anchor_log.append({"what": what, "abs_dev": dev, "tol": tol,
                       "status": "ok" if dev <= tol else "FAIL"})
    if dev > tol:
        raise RuntimeError(f"Verification check failed: {what} deviation {dev:.3e} > tolerance {tol:.3e}")


_FROZEN_STATIC: pd.DataFrame | None = None
_SEED_METRICS: dict = {}
_MATRIX_RMSE: pd.DataFrame | None = None


def _static_frozen_value(arm: str) -> float:
    """Read the RMSE for an arm from 003's frozen boerde_static_metrics.csv (stored at 4 decimal places)."""
    global _FROZEN_STATIC
    if _FROZEN_STATIC is None:
        _FROZEN_STATIC = pd.read_csv(STATIC_CSV, index_col=0)
    return float(_FROZEN_STATIC.loc[de019.FROZEN_ROW_OF[arm], "rmse"])


def _gnn_frozen_value(arm: str, seed: int) -> float:
    """Read the RMSE for the voronoi_* row from 005's per-seed metrics.csv (stored at 4 decimal places)."""
    if seed not in _SEED_METRICS:
        path = MODELS_DIR / CONFIG / f"seed_{seed}" / "metrics.csv"
        _SEED_METRICS[seed] = pd.read_csv(path, index_col=0)
    return float(_SEED_METRICS[seed].loc[de019.SEED_ROW_OF[arm], "rmse"])


def _matrix_value(arm: str, seed: int | None = None) -> float:
    """Read the full-precision RMSE from 019's de_full_matrix.csv (seed=None retrieves the static arm's value)."""
    global _MATRIX_RMSE
    if _MATRIX_RMSE is None:
        df = pd.read_csv(DE_MATRIX_CSV, float_precision="round_trip")
        _MATRIX_RMSE = df[df["metric"] == "rmse"].set_index("arm")
    col = "value" if seed is None else f"value_seed_{seed}"
    return float(_MATRIX_RMSE.loc[arm, col])


def anchor_static(rows: list, anchor_log: list) -> None:
    """Static bases and all 6 multiplicative arms: dual-check against 003's frozen values (4dp) and 019's full-precision values."""
    by = {(r["base_type"], r["signal"]): r for r in rows
          if r["base_type"] in ("uniform", "gpm")}
    for bt in ("uniform", "gpm"):
        base_arm = STATIC_ARM_MAP[(bt, None)]
        got_base = by[(bt, "N")]["rmse_base"]
        _check_anchor(abs(got_base - _static_frozen_value(base_arm)),
                      TOL_FROZEN_4DP,
                      f"{bt} base vs 003 frozen {de019.FROZEN_ROW_OF[base_arm]}",
                      anchor_log)
        _check_anchor(abs(got_base - _matrix_value(base_arm)),
                      TOL_FULLPREC,
                      f"{bt} base vs 019 de_full_matrix {base_arm}", anchor_log)
        for sig in SIGNALS:
            arm = STATIC_ARM_MAP[(bt, sig)]
            got = by[(bt, sig)]["rmse_corrected"]
            _check_anchor(abs(got - _static_frozen_value(arm)),
                          TOL_FROZEN_4DP,
                          f"{bt}+{sig} vs 003 frozen {de019.FROZEN_ROW_OF[arm]}",
                          anchor_log)
            _check_anchor(abs(got - _matrix_value(arm)),
                          TOL_FULLPREC,
                          f"{bt}+{sig} vs 019 de_full_matrix {arm}", anchor_log)


def anchor_gnn(seed: int, rows: list, anchor_log: list) -> None:
    """GNN base + 3 multiplicative arms: dual-check against 005's per-seed values (4dp) and 019's full-precision values."""
    by = {r["signal"]: r for r in rows}
    got_base = by["N"]["rmse_base"]
    _check_anchor(abs(got_base - _gnn_frozen_value("GNN", seed)),
                  TOL_FROZEN_4DP,
                  f"gnn seed{seed} base vs 005 voronoi_GNN", anchor_log)
    _check_anchor(abs(got_base - _matrix_value("GNN", seed)),
                  TOL_FULLPREC,
                  f"gnn seed{seed} base vs 019 de_full_matrix GNN", anchor_log)
    for sig in SIGNALS:
        arm = GNN_ARM_OF[sig]
        got = by[sig]["rmse_corrected"]
        _check_anchor(abs(got - _gnn_frozen_value(arm, seed)),
                      TOL_FROZEN_4DP,
                      f"gnn seed{seed}+{sig} vs 005 {de019.SEED_ROW_OF[arm]}",
                      anchor_log)
        _check_anchor(abs(got - _matrix_value(arm, seed)),
                      TOL_FULLPREC,
                      f"gnn seed{seed}+{sig} vs 019 de_full_matrix {arm}",
                      anchor_log)


# ---------------------------------------------------------------------------
# Phase-diagram point table + confusion matrix (same approach as the UK/AU cases)
# ---------------------------------------------------------------------------
def build_phase_points(df: pd.DataFrame) -> pd.DataFrame:
    """Detail rows -> phase-diagram point table: coordinates + theoretical prediction + observed sign (same rule as the UK case)."""
    out = df.copy()
    out["theory_threshold"] = out["sigma_ratio"] / 2.0
    out["predicted_help"] = out["pearson_log"] > out["theory_threshold"]
    out["actual_help"] = out["delta_rmse"] < 0
    out["prediction_correct"] = out["predicted_help"] == out["actual_help"]
    return out[UK_SCHEMA + ["n_substations", "n_eps_protected_any"]]


def confusion_matrix_of(df: pd.DataFrame) -> dict:
    """2x2 confusion matrix (theoretical prediction x observed delta-RMSE sign; same function as the UK case)."""
    p = df["predicted_help"].values.astype(bool)
    a = df["actual_help"].values.astype(bool)
    cm = {
        "pred_help_actual_help": int((p & a).sum()),
        "pred_help_actual_hurt": int((p & ~a).sum()),
        "pred_hurt_actual_help": int((~p & a).sum()),
        "pred_hurt_actual_hurt": int((~p & ~a).sum()),
    }
    cm["total"] = int(sum(cm.values()))
    cm["accuracy"] = float((p == a).mean())
    return cm


def region_cell(df: pd.DataFrame) -> dict:
    """One summary cell: fraction of points on each side + median coordinates (generated by numeric rules; includes the hurt-side fraction)."""
    return {
        "n_rows": int(len(df)),
        "frac_predicted_help": float(df["predicted_help"].mean()),
        "frac_actual_help": float(df["actual_help"].mean()),
        "frac_predicted_hurt": float((~df["predicted_help"].astype(bool)).mean()),
        "frac_actual_hurt": float((~df["actual_help"].astype(bool)).mean()),
        "frac_prediction_correct": float(df["prediction_correct"].mean()),
        "median_pearson_log": float(df["pearson_log"].median()),
        "median_sigma_r": float(df["sigma_r"].median()),
        "median_sigma_c": float(df["sigma_c"].median()),
        "median_sigma_ratio": float(df["sigma_ratio"].median()),
        "median_delta_rmse": float(df["delta_rmse"].median()),
        "mean_delta_rmse": float(df["delta_rmse"].mean()),
    }


def fisher_ci95(rho: float, n: int) -> tuple[float, float]:
    """Approximate 95% CI for rho under the Fisher z transform (used for the small-sample registration; generated by numeric rules)."""
    z = float(np.arctanh(rho))
    se = 1.0 / np.sqrt(n - 3)
    return float(np.tanh(z - 1.96 * se)), float(np.tanh(z + 1.96 * se))


