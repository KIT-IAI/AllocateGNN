"""Standard figures for the numbered DataOverview display notebooks.

Each ``plot_*`` function returns a ``matplotlib.figure.Figure`` built from
already-landed artifacts; ``save_figure`` writes it under
``results/1_DataOverview/<dir>/figures``.  The notebooks only call and save,
so the figures can be regenerated by code alone.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable, Mapping, Sequence

import geopandas as gpd
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.figure import Figure
from matplotlib.patches import Patch

KIT_GREEN = "#009682"
KIT_BLUE = "#4664AA"
KIT_RED = "#A11035"
KIT_ORANGE = "#DF9B1B"
GREY_5 = "#f2f2f2"
GREY_30 = "#b3b3b3"
GREY_60 = "#666666"

LANDUSE_COLORS = {
    "residential": KIT_BLUE,
    "commercial": KIT_ORANGE,
    "industrial": KIT_RED,
    "agricultural": KIT_GREEN,
    "others": GREY_30,
}
CUZ_COLORS = {"covered": KIT_GREEN, "unknown": KIT_ORANGE, "zero": GREY_30}

_RC = {
    "font.size": 9,
    "axes.spines.top": False,
    "axes.spines.right": False,
    "pdf.fonttype": 42,
    "figure.dpi": 110,
}


def _style() -> None:
    plt.rcParams.update(_RC)


def save_figure(fig: Figure, path: Path | str, *, dpi: int = 170) -> Path:
    """Save ``fig`` as PNG (parents created) and return the path; the figure stays open."""

    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(target, dpi=dpi, bbox_inches="tight")
    return target


def _lonlat_axes(ax, title: str) -> None:
    ax.set_xlabel("Longitude [°E]")
    ax.set_ylabel("Latitude [°N]")
    ax.set_title(title)
    ax.set_aspect("equal")


