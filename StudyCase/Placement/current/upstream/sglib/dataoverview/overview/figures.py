def plot_stacked_shares(
    table: pd.DataFrame,
    *,
    index_column: str,
    columns: Sequence[str],
    labels: Sequence[str] | None = None,
    colors: Mapping[str, str] | None = None,
    normalise: bool = True,
    title: str,
    xlabel: str,
) -> Figure:
    """Horizontal stacked bars of ``columns`` per row (shares when ``normalise``)."""

    _style()
    names = table[index_column].astype(str).tolist()
    values = table[list(columns)].to_numpy(dtype=float)
    if normalise:
        totals = values.sum(axis=1, keepdims=True)
        totals[totals == 0] = 1.0
        values = values / totals
    y = np.arange(len(names))
    fig, ax = plt.subplots(figsize=(7.0, 0.32 * len(names) + 1.4))
    left = np.zeros(len(names))
    labels = list(labels) if labels is not None else list(columns)
    for column, label in zip(columns, labels):
        column_values = values[:, list(columns).index(column)]
        color = (colors or {}).get(label) or (colors or {}).get(column)
        ax.barh(y, column_values, left=left, height=0.68, label=label, color=color)
        left = left + column_values
    ax.set_yticks(y, names)
    ax.invert_yaxis()
    ax.set_xlabel(xlabel)
    if normalise:
        ax.set_xlim(0, 1)
    ax.set_title(title)
    ax.legend(loc="center left", bbox_to_anchor=(1.01, 0.5), frameon=False, fontsize=7)
    fig.tight_layout()
    return fig


def plot_cell_values(
    grid: gpd.GeoDataFrame,
    values: np.ndarray,
    *,
    title: str,
    label: str,
    log: bool = False,
    cmap: str = "viridis",
    point_size: float = 0.8,
    figsize: tuple[float, float] = (6.0, 5.0),
) -> Figure:
    """Grid cells coloured by a per-cell value (Built-S fraction, NTL radiance, ...)."""

    _style()
    frame = grid.to_crs("EPSG:4326")
    data = np.asarray(values, dtype=float)
    if log:
        data = np.log10(np.clip(data, 0, None) + 1e-3)
        label = f"log10({label} + 1e-3)"
    fig, ax = plt.subplots(figsize=figsize)
    scatter = ax.scatter(frame.geometry.x, frame.geometry.y, c=data, s=point_size, cmap=cmap, linewidths=0)
    fig.colorbar(scatter, ax=ax, shrink=0.8, label=label)
    _lonlat_axes(ax, title)
    fig.tight_layout()
    return fig


def plot_cell_categories(
    grid: gpd.GeoDataFrame,
    categories: Sequence[str] | np.ndarray,
    *,
    title: str,
    colors: Mapping[str, str],
    order: Sequence[str] | None = None,
    point_size: float = 0.8,
    figsize: tuple[float, float] = (6.0, 5.0),
) -> Figure:
    """Grid cells coloured by a categorical label per cell (dominant land use, C/U/Z class, ...)."""

    _style()
    frame = grid.to_crs("EPSG:4326")
    labels = np.asarray(categories, dtype=str)
    if len(labels) != len(frame):
        raise ValueError(f"categories has {len(labels)} entries for {len(frame)} cells")
    names = list(order) if order is not None else list(dict.fromkeys(labels))
    fig, ax = plt.subplots(figsize=figsize)
    for name in names:
        mask = labels == name
        if not mask.any():
            continue
        ax.scatter(
            frame.geometry.x[mask], frame.geometry.y[mask], s=point_size,
            color=colors.get(name, GREY_60), linewidths=0, label=f"{name} ({int(mask.sum()):,})",
        )
    ax.legend(loc="center left", bbox_to_anchor=(1.01, 0.5), frameon=False, fontsize=7, markerscale=6)
    _lonlat_axes(ax, title)
    fig.tight_layout()
    return fig


def plot_value_histograms(
    series: Mapping[str, np.ndarray],
    *,
    title: str,
    bins: int = 40,
    log_x: bool = False,
) -> Figure:
    """One histogram panel per named value array (shared bins)."""

    _style()
    names = list(series)
    fig, axes = plt.subplots(1, len(names), figsize=(3.6 * len(names), 3.0), squeeze=False)
    for ax, name in zip(axes[0], names):
        data = np.asarray(series[name], dtype=float)
        if log_x:
            data = np.log10(np.clip(data, 0, None) + 1e-3)
        ax.hist(data, bins=bins, color=KIT_BLUE)
        ax.set_title(name, fontsize=8)
        ax.set_ylabel("cells")
        ax.set_xlabel("log10(value + 1e-3)" if log_x else "value")
    fig.suptitle(title, y=1.02)
    fig.tight_layout()
    return fig


