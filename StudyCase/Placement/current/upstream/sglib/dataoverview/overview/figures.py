def plot_regions_and_stations(
    regions: gpd.GeoDataFrame,
    stations: gpd.GeoDataFrame,
    *,
    title: str,
    highlight_column: str | None = None,
    highlight_values: Iterable[str] | None = None,
    highlight_label: str = "analysis regions",
    region_column: str | None = None,
    station_size: float = 0.4,
    figsize: tuple[float, float] = (5.5, 6.5),
) -> Figure:
    """Region polygons (grey) with station points (blue); optional green highlight groups.

    When ``region_column`` is given, only stations assigned to a region (non-null
    in that column) are drawn; the legend states how many were left out.
    """

    _style()
    outside = 0
    if region_column and region_column in stations:
        assigned = stations[region_column].notna()
        outside = int((~assigned).sum())
        stations = stations.loc[assigned]
    fig, ax = plt.subplots(figsize=figsize)
    regions.to_crs("EPSG:4326").plot(ax=ax, color=GREY_5, edgecolor=GREY_30, linewidth=0.4)
    handles = [Patch(facecolor=GREY_5, edgecolor=GREY_30, label="regions")]
    if highlight_column and highlight_values is not None:
        wanted = set(map(str, highlight_values))
        subset = regions.loc[regions[highlight_column].astype(str).isin(wanted)]
        subset.to_crs("EPSG:4326").plot(ax=ax, color=KIT_GREEN, alpha=0.55, edgecolor=GREY_30, linewidth=0.4)
        handles.append(Patch(facecolor=KIT_GREEN, alpha=0.55, label=highlight_label))
    caption = f"{len(regions):,} regions"
    if len(stations):
        stations.to_crs("EPSG:4326").plot(ax=ax, color=KIT_BLUE, markersize=station_size)
        handles.append(plt.Line2D([], [], marker="o", color=KIT_BLUE, linestyle="", markersize=3, label="stations"))
        caption += f", {len(stations):,} stations"
        if outside:
            caption += f" ({outside:,} outside regions omitted)"
    # Legend labels stay at most three words so the box never hides the map;
    # counts go into a second title line instead.
    ax.legend(handles=handles, loc="upper left", frameon=False, fontsize=7)
    _lonlat_axes(ax, f"{title}\n{caption}")
    fig.tight_layout()
    return fig


def plot_group_zoom(
    regions: gpd.GeoDataFrame,
    stations: gpd.GeoDataFrame,
    *,
    group_column: str | None,
    group_value: str,
    label_column: str | None = None,
    region_column: str | None = None,
    max_labels: int = 40,
    figsize: tuple[float, float] = (5.5, 4.5),
) -> Figure:
    """One analysis region with its sub-regions labelled and its stations as points.

    With ``group_column=None`` the whole regions table is one analysis region
    (single-region countries); stations are then filtered by ``region_column``.
    Source-row labels are drawn only when there are at most ``max_labels``.
    """

    _style()
    if group_column:
        region = regions.loc[regions[group_column].astype(str) == str(group_value)]
        points = stations.loc[stations[group_column].astype(str) == str(group_value)] if group_column in stations else stations.iloc[0:0]
    else:
        region = regions
        points = stations.loc[stations[region_column].notna()] if region_column and region_column in stations else stations
    region = region.to_crs("EPSG:4326")
    points = points.to_crs("EPSG:4326")
    fig, ax = plt.subplots(figsize=figsize)
    region.plot(ax=ax, color=GREY_5, edgecolor=GREY_60, linewidth=0.6)
    if len(points):
        points.plot(ax=ax, color=KIT_GREEN, markersize=6)
    if label_column and label_column in region and len(region) <= max_labels:
        for geometry, label in zip(region.geometry, region[label_column].astype(str)):
            centroid = geometry.representative_point()
            ax.annotate(label, (centroid.x, centroid.y), fontsize=6, ha="center", va="center", color=GREY_60)
    _lonlat_axes(ax, f"{group_value}: {len(region)} source rows, {len(points):,} stations")
    fig.tight_layout()
    return fig


