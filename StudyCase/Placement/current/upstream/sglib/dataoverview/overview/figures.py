def plot_grid_profile(profile: pd.DataFrame, *, target_points: int, title: str) -> Figure:
    """Side-by-side horizontal bars: projected step length and realised cell count per region."""

    _style()
    labels = profile["region"].astype(str).tolist()
    step = profile["projected_step_m"].to_numpy(dtype=float)
    cells = profile["n_cells"].to_numpy(dtype=float)
    y = np.arange(len(labels))
    fig, (ax_step, ax_count) = plt.subplots(1, 2, figsize=(8.2, 0.32 * len(labels) + 1.6), sharey=True, layout="constrained")
    ax_step.barh(y, step, color=KIT_GREEN, height=0.68)
    ax_step.set_yticks(y, labels)
    ax_step.invert_yaxis()
    ax_step.set_xlabel("Projected grid step [m]")
    ax_step.set_title("Bounded equal-area step")
    ax_step.set_xlim(0, step.max() * 1.15)
    for yi, value in zip(y, step):
        ax_step.text(value + step.max() * 0.01, yi, f"{value:.0f}", va="center", fontsize=7)
    ax_count.barh(y, cells, color=KIT_BLUE, height=0.68)
    ax_count.axvline(target_points, color=KIT_RED, linewidth=0.9, linestyle="--", label=f"target {target_points:,}")
    ax_count.set_xlabel("Grid cells")
    ax_count.set_title("Realised cell count")
    ax_count.set_xlim(0, cells.max() * 1.18)
    ax_count.legend(loc="lower right", frameon=False, fontsize=7)
    for yi, value in zip(y, cells):
        ax_count.text(value + cells.max() * 0.01, yi, f"{value:,.0f}", va="center", fontsize=7)
    fig.suptitle(title)
    return fig


def plot_grid_points(
    grid: gpd.GeoDataFrame,
    *,
    source_key: str,
    region: str,
    outline: gpd.GeoDataFrame | None = None,
    point_size: float = 0.6,
    figsize: tuple[float, float] = (6.0, 5.0),
) -> Figure:
    """Grid cell centroids coloured by their source row, with the region outline."""

    _style()
    frame = grid.to_crs("EPSG:4326")
    keys = frame[source_key].astype(str)
    order = list(dict.fromkeys(keys))
    cmap = plt.get_cmap("tab20", max(len(order), 1))
    fig, ax = plt.subplots(figsize=figsize)
    if outline is not None and len(outline):
        outline.to_crs("EPSG:4326").plot(ax=ax, facecolor="none", edgecolor=GREY_60, linewidth=0.6)
    for index, key in enumerate(order):
        subset = frame.loc[keys == key]
        ax.scatter(subset.geometry.x, subset.geometry.y, s=point_size, color=cmap(index), linewidths=0, label=key)
    if len(order) <= 24:
        ax.legend(loc="center left", bbox_to_anchor=(1.01, 0.5), frameon=False, fontsize=6, markerscale=6, title=source_key)
    _lonlat_axes(ax, f"{region}: {len(frame):,} cells over {len(order)} {source_key} rows")
    fig.tight_layout()
    return fig


